#!/usr/bin/env python3
"""
Script de diagnóstico para verificar el estado de node_modules en el servidor
"""

import os
import json

def debug_node_modules():
    """Diagnosticar el estado de node_modules"""
    
    print("🔍 DIAGNÓSTICO DE NODE_MODULES")
    print("=" * 50)
    
    # Verificar directorio actual
    current_dir = os.getcwd()
    print(f"📁 Directorio actual: {current_dir}")
    
    # Verificar directorio del script
    script_dir = os.path.dirname(os.path.abspath(__file__))
    print(f"📁 Directorio del script: {script_dir}")
    
    # Verificar node_modules en diferentes ubicaciones
    possible_locations = [
        os.path.join(current_dir, 'node_modules'),
        os.path.join(script_dir, 'node_modules'),
        '/app/node_modules',  # Render.com ubicación típica
        '/opt/render/project/src/node_modules'  # Otra ubicación posible
    ]
    
    print("\n📂 BUSCANDO NODE_MODULES:")
    for location in possible_locations:
        exists = os.path.exists(location)
        print(f"   {location}: {'✅ EXISTE' if exists else '❌ NO EXISTE'}")
        
        if exists:
            try:
                items = os.listdir(location)
                print(f"      - Contiene {len(items)} elementos")
                
                # Verificar dependencias críticas
                critical_deps = ['bootstrap', 'jquery', 'leaflet', 'jsplumb']
                for dep in critical_deps:
                    dep_path = os.path.join(location, dep)
                    dep_exists = os.path.exists(dep_path)
                    print(f"      - {dep}: {'✅' if dep_exists else '❌'}")
                    
            except Exception as e:
                print(f"      - Error leyendo directorio: {e}")
    
    # Verificar package.json
    print("\n📄 VERIFICANDO PACKAGE.JSON:")
    package_locations = [
        os.path.join(current_dir, 'package.json'),
        os.path.join(script_dir, 'package.json')
    ]
    
    for location in package_locations:
        exists = os.path.exists(location)
        print(f"   {location}: {'✅ EXISTE' if exists else '❌ NO EXISTE'}")
        
        if exists:
            try:
                with open(location, 'r') as f:
                    package_data = json.load(f)
                    deps = package_data.get('dependencies', {})
                    print(f"      - {len(deps)} dependencias declaradas")
                    
                    critical_deps = ['bootstrap', 'jquery', 'leaflet', 'jsplumb']
                    for dep in critical_deps:
                        version = deps.get(dep, 'NO ENCONTRADO')
                        print(f"      - {dep}: {version}")
                        
            except Exception as e:
                print(f"      - Error leyendo package.json: {e}")
    
    # Verificar variables de entorno
    print("\n🌍 VARIABLES DE ENTORNO:")
    env_vars = ['NODE_ENV', 'NPM_CONFIG_PRODUCTION', 'PATH']
    for var in env_vars:
        value = os.environ.get(var, 'NO DEFINIDA')
        print(f"   {var}: {value}")
    
    print("\n" + "=" * 50)
    print("✅ Diagnóstico completado")

if __name__ == "__main__":
    debug_node_modules()
